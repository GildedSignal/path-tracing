param(
  [Parameter(Mandatory=$true)][string]$Results,
  [string]$Output
)
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\common.ps1"
if (-not $Output) { $Output = Join-Path $Root 'lab\wiki' }
$key = $env:ZAI_API_KEY
if (-not $key) { try { $key = Get-GlmKey } catch { throw 'Cannot read the stored GLM key; refusing to write wiki output.' } }
$secretPattern = '(?i)(?:\b(?:sk|zai|ghp|github_pat)-[A-Za-z0-9_-]{12,}\b|\b(?:api[_-]?key|access[_-]?token|authorization|password|secret)\s*[:=]\s*["'']?(?:Bearer\s+)?[A-Za-z0-9_./+\-=]{12,})'
function Safe([string]$s) {
  if (($key -and $s.Contains($key)) -or $s -match $secretPattern) { throw 'Refusing to write a line containing a possible credential.' }
  return $s
}
function Field([string[]]$lines, [string]$label) {
  foreach ($line in $lines) {
    if ($line -match ('(?i)^\s*(?:[-*]\s*)?(?:\*\*)?' + $label + '(?:\*\*)?\s*:\s*(?:\*\*)?\s*(.+?)\s*$')) { return $Matches[1] }
    if ($line -match ('(?i)^\s*(?:[-*]\s*)?\*\*' + $label + ':\*\*\s*(.+?)\s*$')) { return $Matches[1] }
  }
  return ''
}
function Short([string]$s) {
  $s = ($s -replace '\s+', ' ').Trim()
  if ($s.Length -gt 300) { $s = $s.Substring(0,297).TrimEnd() + '...' }
  return $s
}
function ReadLines([string]$path) {
  if (Test-Path -LiteralPath $path -PathType Leaf) { return @(Get-Content -LiteralPath $path -Encoding UTF8) }
  return @()
}
$runs = @()
foreach ($dir in @(Get-ChildItem -LiteralPath $Results -Directory | Sort-Object Name -Descending)) {
  if ($dir.Name -notmatch '^local-(\d{8})-(\d{4})-\d+-\d+-(.+)$') { continue }
  $date = $Matches[1].Insert(6,'-').Insert(4,'-'); $lens = $Matches[3]
  $dossier = @(ReadLines (Join-Path $dir.FullName 'dossier.md'))
  $check = @(ReadLines (Join-Path $dir.FullName 'check.md'))
  $claim = Field $dossier 'Claim'
  $missing = $dossier.Count -eq 0 -or $claim -eq 'The author produced no dossier.'
  $limited = $false
  $phases = @(ReadLines (Join-Path $dir.FullName 'phases.txt'))
  foreach ($log in @('author.log','checker.log')) {
    $phase = $log -replace '\.log$', ''
    $completed = @($phases | Where-Object { $_ -match "^$phase exit: 0\s*$" }).Count -gt 0
    if (-not $completed -and @(ReadLines (Join-Path $dir.FullName $log) | Where-Object { $_ -match '429|rate_limit' }).Count -gt 0) { $limited = $true }
  }
  $grade = Field $check 'Grade'
  if ($limited) { $grade = 'rate-limited' } elseif ($missing) { $grade = 'no dossier' } elseif (-not $grade) { $grade = 'ungraded' }
  $falsifier = Field $dossier 'Falsifier'
  $discrepancy = Field $check '(?:Key discrepancy|Discrepancy)'
  if (-not $discrepancy) {
    for ($i=0; $i -lt $check.Count; $i++) {
      if ($check[$i] -match '(?i)^#{1,4}\s+.*discrepanc') {
        for ($j=$i+1; $j -lt $check.Count; $j++) { if ($check[$j].Trim()) { $discrepancy = $check[$j]; break } }
        break
      }
    }
  }
  $runs += [pscustomobject]@{ Id=$dir.Name; Date=$date; Lens=$lens; Grade=$grade; Claim=(Short $claim); Falsifier=(Short $falsifier); Discrepancy=(Short $discrepancy) }
}
$files = @{}
foreach ($group in @($runs | Group-Object Lens | Sort-Object Name)) {
  $lines = New-Object 'System.Collections.Generic.List[string]'
  $lines.Add('<!-- Generated by scripts/lab-wiki.ps1; do not edit. -->'); $lines.Add("# $($group.Name)"); $lines.Add('')
  foreach ($run in $group.Group) {
    $lines.Add("## $($run.Id) ($($run.Date))"); $lines.Add("- Grade: $($run.Grade)")
    if ($run.Claim) { $lines.Add("- Claim: $($run.Claim)") }
    if ($run.Falsifier) { $lines.Add("- Falsifier: $($run.Falsifier)") }
    if ($run.Discrepancy) { $lines.Add("- Checker discrepancy: $($run.Discrepancy)") }
    $lines.Add("- Run folder: $($run.Id)"); $lines.Add('')
  }
  $files["$($group.Name).md"] = $lines.ToArray()
}
$index = New-Object 'System.Collections.Generic.List[string]'
$index.Add('<!-- Generated by scripts/lab-wiki.ps1; do not edit. -->'); $index.Add('# Lab wiki'); $index.Add(''); $index.Add('## Lenses'); $index.Add('')
foreach ($group in @($runs | Group-Object Lens | Sort-Object Name)) {
  $counts = @($group.Group | Group-Object Grade | Sort-Object Name | ForEach-Object { "$($_.Name): $($_.Count)" }) -join ', '
  $index.Add("- [$($group.Name)]($($group.Name).md) — $counts; last $($group.Group[0].Date)")
}
$index.Add(''); $index.Add('## Reproduced results'); $index.Add('')
foreach ($run in @($runs | Where-Object Grade -eq 'reproduced')) { $index.Add("- $($run.Date) [$($run.Lens)]($($run.Lens).md) ($($run.Id)): $($run.Claim)") }
$files['index.md'] = $index.ToArray()
# Validate every line before creating or changing any output.
foreach ($name in $files.Keys) { [void](Safe $name); foreach ($line in $files[$name]) { [void](Safe $line) } }
New-Item -ItemType Directory -Force -Path $Output | Out-Null
foreach ($name in @($files.Keys | Sort-Object)) {
  [IO.File]::WriteAllText((Join-Path $Output $name), (($files[$name] -join "`n") + "`n"), (New-Object Text.UTF8Encoding $false))
}
foreach ($old in @(Get-ChildItem -LiteralPath $Output -Filter '*.md' -File)) {
  if (-not $files.ContainsKey($old.Name) -and (Get-Content -LiteralPath $old.FullName -TotalCount 1) -eq '<!-- Generated by scripts/lab-wiki.ps1; do not edit. -->') { Remove-Item -LiteralPath $old.FullName }
}



